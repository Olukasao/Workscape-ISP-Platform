export const buildSemiDedicadoProductName = (banda) => (
  `COMER | I${banda} | SLA24 | PPPOE-IPV | RTW6`
);

export const findSemiDedicadoPrice = (banda, prazo) => (
  semiDedicadoPricing.find((item) => (
    item.banda === banda && Number(item.prazo) === Number(prazo)
  )) || null
);

export const calculateSemiDedicadoPrice = (banda, prazo, valorNegociado = null) => {
  const item = findSemiDedicadoPrice(banda, prazo);

  if (!item) {
    return {
      error: 'Não foi possível encontrar preço para esta banda e prazo.',
    };
  }

  const minValue = item.min;
  const maxValue = item.max;
  const averageValue = (minValue + maxValue) / 2;
  const hasNegotiatedValue = valorNegociado !== null
    && valorNegociado !== undefined
    && valorNegociado !== '';
  const negotiatedValue = hasNegotiatedValue ? Number(valorNegociado) : null;
  let negotiatedStatus = null;

  if (hasNegotiatedValue && Number.isFinite(negotiatedValue)) {
    if (negotiatedValue < minValue) {
      negotiatedStatus = 'abaixo';
    } else if (negotiatedValue <= maxValue) {
      negotiatedStatus = 'dentro';
    } else {
      negotiatedStatus = 'acima';
    }
  }

  return {
    banda: item.banda,
    contractMonths: Number(item.prazo),
    productName: buildSemiDedicadoProductName(item.banda),
    minValue,
    averageValue,
    maxValue,
    negotiatedValue,
    negotiatedStatus,
  };
};
