export function findTool(pathname) {
  if (/^\/admin\/usuarios\/[^/]+\/mensagens$/.test(pathname)) return adminUserHistory;
  return toolItems.find(
    (i) =>
      pathname === i.path ||
      (i.path === "/wiki" && pathname.startsWith("/wiki/")),
  );
}

export function usePermittedTools() {
  const user = useSession((s) => s.user),
    access = useAccess();
  const allowed = allowedIds(access.data);
  return {
    access,
    tools: toolItems.filter((i) => canUseTool(i, allowed, user?.perfil)),
    permitted: (i) => canUseTool(i, allowed, user?.perfil),
  };
}

